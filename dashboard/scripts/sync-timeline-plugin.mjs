import { readFile, writeFile, copyFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
const root = new URL('../', import.meta.url);
const plugin = new URL('site/content/.obsidian/plugins/research-timeline/', root);
const base = await readFile(new URL('site/static/css/timeline.css', root), 'utf8');
const editor = await readFile(new URL('editor.css', plugin), 'utf8');
const parser = await readFile(new URL('source.js', plugin), 'utf8');
const entry = await readFile(new URL('plugin.js', plugin), 'utf8');
const bundledParser = `(() => { const module = { exports: {} };\n${parser}\nreturn module.exports; })()`;
await writeFile(new URL('main.js', plugin), '// Generated by scripts/sync-timeline-plugin.mjs.\n' + entry.replace("require('./source')", () => bundledParser));
await writeFile(new URL('styles.css', plugin), base.replace(/@font-face\s*\{[^}]*\}/, '') + '\n' + editor);
for (const name of ['Geist-latin.woff2', 'geist-OFL.txt', 'lucide-LICENSE.txt', 'shadcn-LICENSE.txt']) {
  await copyFile(new URL('site/static/vendor/trace/' + name, root), new URL(name, plugin));
}
console.log('Synced timeline styling and fonts to', fileURLToPath(plugin));
